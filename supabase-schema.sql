create or replace function public.calculate_delivery_fee(delivery_state text, delivery_city text)
returns numeric
language plpgsql
immutable
as $$
declare
  normalized_state text := lower(trim(coalesce(delivery_state, '')));
  normalized_city text := lower(trim(coalesce(delivery_city, '')));
begin
  if normalized_state in ('plateau', 'plateau state') then
    if normalized_city like '%jos north%' then return 2000; end if;
    if normalized_city like '%rayfield%' then return 2500; end if;
    if normalized_city = 'jos' or normalized_city like 'jos %' then return 2000; end if;
    return 3000;
  end if;
  if normalized_state = 'lagos' or normalized_city = 'lagos' then return 5000; end if;
  if normalized_state = 'abuja' or normalized_city = 'abuja' then return 5000; end if;
  if normalized_state = 'kaduna' or normalized_city = 'kaduna' then return 5000; end if;
  if normalized_state = 'kano' or normalized_city = 'kano' then return 5500; end if;
  if normalized_state in ('rivers', 'port harcourt') or normalized_city = 'port harcourt' then return 5500; end if;
  return 0;
end;
$$;

create or replace function public.create_verified_order(order_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  current_year text := to_char(current_date, 'YYYY');
  next_sequence integer;
  new_order public.orders;
  requested_item jsonb;
  product_row public.products;
  calculated_subtotal numeric(12, 2) := 0;
  item_quantity integer;
  delivery_fee numeric(12, 2);
begin
  perform pg_advisory_xact_lock(hashtext('arcadia-order-number-' || current_year));
  delivery_fee := public.calculate_delivery_fee(order_payload->'delivery'->>'state', order_payload->'delivery'->>'city');

  select coalesce(max((split_part(order_number, '-', 3))::integer), 0) + 1
    into next_sequence
    from public.orders
   where order_number like 'ARC-' || current_year || '-%';

  for requested_item in select * from jsonb_array_elements(order_payload->'items') loop
    select * into product_row from public.products where id = (requested_item->>'id')::bigint and is_active = true for update;
    item_quantity := (requested_item->>'quantity')::integer;
    if product_row.id is null or item_quantity is null or item_quantity < 1 then
      raise exception 'Invalid product in order';
    end if;
    if not exists (select 1 from public.inventory where product_id = product_row.id and quantity >= item_quantity) then
      raise exception 'Insufficient inventory';
    end if;
    calculated_subtotal := calculated_subtotal + (product_row.price * item_quantity);
  end loop;

  if calculated_subtotal + delivery_fee <> (order_payload->>'verified_amount')::numeric then
    raise exception 'Verified payment amount does not match order total';
  end if;

  insert into public.orders (order_number, user_id, customer_name, phone, email, state, city, address, subtotal, delivery_fee, total, status)
  values ('ARC-' || current_year || '-' || lpad(next_sequence::text, 5, '0'), auth.uid(), order_payload->'customer'->>'name', order_payload->'customer'->>'phone', order_payload->'customer'->>'email', order_payload->'delivery'->>'state', order_payload->'delivery'->>'city', order_payload->'delivery'->>'address', calculated_subtotal, delivery_fee, calculated_subtotal + delivery_fee, 'Processing')
  returning * into new_order;

  for requested_item in select * from jsonb_array_elements(order_payload->'items') loop
    select * into product_row from public.products where id = (requested_item->>'id')::bigint;
    item_quantity := (requested_item->>'quantity')::integer;
    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity)
    values (new_order.id, product_row.id, product_row.name, product_row.price, item_quantity);
    update public.inventory set quantity = quantity - item_quantity, updated_at = now() where product_id = product_row.id;
  end loop;

  insert into public.payments (order_id, method, reference, amount, status)
  values (new_order.id, order_payload->>'payment_method', order_payload->>'reference', new_order.total, 'Paid');

  return to_jsonb(new_order);
end;
$$;
