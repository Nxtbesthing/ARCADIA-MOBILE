  name text not null,
  phone text not null,
  email text not null,
  device text not null,
  problem text not null,
  device_details text,
  problem_details text,
  additional_information text,
  preferred_date date,
  diagnosis text,
  repair_cost numeric(12, 2) check (repair_cost is null or repair_cost >= 0),
  status text not null default 'Requested' check (status in ('Requested', 'Received', 'Diagnosing', 'Awaiting Approval', 'Repairing', 'Testing', 'Ready', 'Completed', 'Cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
